export const statusCounts = (list: Patient[] = patients) =>
  list.reduce<Record<ReviewStatus, number>>(
    (acc, p) => {
      acc[p.status] += 1;
      return acc;
    },
    { urgent: 0, review: 0, routine: 0, "more-data": 0 }
  );

export const openAlerts = (list: Alert[] = alerts) => list.filter((a) => !a.acknowledged);

export const todaysAppointments = (list: Appointment[] = appointments) =>
  list.filter((a) => isSameDay(new Date(a.at), TODAY)).sort((a, b) => a.at.localeCompare(b.at));

export const upcomingAppointments = (list: Appointment[] = appointments) =>
  list
    .filter((a) => a.state === "upcoming" && new Date(a.at) >= TODAY)
    .sort((a, b) => a.at.localeCompare(b.at));

export const latestReading = (p: Patient) => p.readings[p.readings.length - 1];

export const latestCheckInLabel = (p: Patient) => {
  const date = new Date(p.lastCheckIn);
  const today = isSameDay(date, TODAY);
  return `${today ? "Today" : "Yesterday"} · ${clock(date)}`;
};
