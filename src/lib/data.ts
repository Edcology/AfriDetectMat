/**
 * Align each patient's reading series so the most recent recording lands on the
 * same day as their last check-in. Keeps the demo set internally coherent without
 * hand-writing 60 timestamps.
 */
const dayIndex = (iso: string) =>
  Math.round((new Date(iso).setHours(0, 0, 0, 0) - new Date(2026, 10, 17).getTime()) / 86_400_000);

for (const patient of patients) {
  const newest = patient.readings.at(-1);
  if (!newest) continue;
  const shift = (dayIndex(patient.lastCheckIn) - dayIndex(newest.at)) * 86_400_000;
  if (shift === 0) continue;
  patient.readings = patient.readings.map((reading) => ({
    ...reading,
    at: new Date(new Date(reading.at).getTime() + shift).toISOString(),
  }));
}

